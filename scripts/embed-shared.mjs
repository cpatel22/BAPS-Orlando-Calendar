/**
 * 1) Embeds shared/*.js into lib/shared-sources.ts so Vercel serverless
 *    functions (calendar.ics) don't need those files on disk at runtime.
 * 2) Copies them into public/ so /events.js and /calendar-core.js are real
 *    static assets on Vercel (CDN serves them; no route-handler lookup).
 */
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sharedDir = join(root, "shared");
const publicDir = join(root, "public");

const eventsPath = join(sharedDir, "events.js");
const corePath = join(sharedDir, "calendar-core.js");

const events = readFileSync(eventsPath, "utf8");
const core = readFileSync(corePath, "utf8");

const out = `/* AUTO-GENERATED by scripts/embed-shared.mjs — do not edit */
export const EVENTS_JS = ${JSON.stringify(events)};
export const CORE_JS = ${JSON.stringify(core)};
`;

writeFileSync(join(root, "lib", "shared-sources.ts"), out);
copyFileSync(eventsPath, join(publicDir, "events.js"));
copyFileSync(corePath, join(publicDir, "calendar-core.js"));
console.log("embedded shared/*.js → lib/shared-sources.ts");
console.log("copied shared/*.js → public/");
