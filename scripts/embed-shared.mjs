/**
 * Embeds shared/*.js into lib/shared-sources.ts so Vercel serverless
 * functions don't need those files on disk at runtime.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const events = readFileSync(join(root, "shared", "events.js"), "utf8");
const core = readFileSync(join(root, "shared", "calendar-core.js"), "utf8");

const out = `/* AUTO-GENERATED by scripts/embed-shared.mjs — do not edit */
export const EVENTS_JS = ${JSON.stringify(events)};
export const CORE_JS = ${JSON.stringify(core)};
`;

writeFileSync(join(root, "lib", "shared-sources.ts"), out);
console.log("embedded shared/*.js → lib/shared-sources.ts");
